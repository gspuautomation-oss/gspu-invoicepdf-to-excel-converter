/**
 * Generates a real binary PDF buffer from a SampleInvoiceBlueprint using pdf-lib.
 */
export async function generateInvoicePdfBytes(
  bp: SampleInvoiceBlueprint
): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([612, 792]);
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  let y = 755;
  const left = 24;
  const lineStep = 15;

  const drawLine = (text: string, isBold = false, size = 9) => {
    page.drawText(text, {
      x: left,
      y,
      size,
      font: isBold ? boldFont : font,
      color: rgb(0.06, 0.09, 0.16),
    });
    y -= lineStep;
  };

  drawLine(bp.docType, true, 13);
  drawLine(`Invoice No: ${bp.invoiceNumber}`);
  drawLine(`Invoice Date: ${bp.invoiceDate}`);
  drawLine(`Due Date: ${bp.dueDate}`);
  drawLine(`PO Number: ${bp.poNumber}`);
  drawLine(`Reference No: ${bp.referenceNumber}`);
  drawLine(`Currency: ${bp.currency}`);
  y -= 4;

  drawLine(`Supplier Name: ${bp.supplierName}`, true);
  drawLine(`Supplier Address: ${bp.supplierAddress}`);
  drawLine(`Supplier GSTIN: ${bp.supplierTaxId}`);
  drawLine(`Supplier Contact: ${bp.supplierContact}`);
  y -= 4;

  drawLine(`Customer Name: ${bp.customerName}`, true);
  drawLine(`Customer Address: ${bp.customerAddress}`);
  drawLine(`Customer GSTIN: ${bp.customerTaxId}`);
  drawLine(`Shipping Details: ${bp.shippingDetails}`);
  y -= 6;

  drawLine(
    'S.No | Description | HSN/SAC | Qty | Unit | Rate | Discount | Taxable | Tax% | CGST | SGST | IGST | VAT | Total',
    true,
    7
  );

  for (const item of bp.items) {
    drawLine(
      `ITEM_ROW | ${item.serialNumber} | ${item.description} | ${item.hsnSac} | ${item.quantity} | ${item.unit} | ${item.rate} | ${item.discount} | ${item.taxableAmount} | ${item.taxPercentage} | ${item.cgstAmount} | ${item.sgstAmount} | ${item.igstAmount} | ${item.vatAmount} | ${item.totalLineAmount}`,
      false,
      6.5
    );
  }

  y -= 6;
  drawLine(`Subtotal: ${bp.subtotal}`);
  drawLine(`Taxable Value: ${bp.taxableValue}`);
  drawLine(`Total Discounts: ${bp.totalDiscounts}`);
  drawLine(`Total Taxes: ${bp.totalTaxes}`);
  drawLine(`Additional Charges: ${bp.additionalCharges}`);
  drawLine(`Round-Off: ${bp.roundOff}`);
  drawLine(`Grand Total: ${bp.grandTotal}`, true);
  drawLine(`Amount Paid: ${bp.amountPaid}`);
  drawLine(`Balance Due: ${bp.balanceDue}`);
  y -= 4;

  drawLine(`Bank Details: ${bp.bankDetails}`);
  drawLine(`Payment Terms: ${bp.paymentTerms}`);
  drawLine(`Notes: ${bp.notes}`);
  drawLine(`Remarks: ${bp.remarks}`);

  if (bp.extraFields) {
    for (const ef of bp.extraFields) {
      drawLine(`${ef.key}: ${ef.value}`);
    }
  }

  return await pdfDoc.save();
}
